export function getScalesForCourse(courseId: string): CourseScaleItem[] {
  return COURSE_SCALES_DATA.filter((scale) => scale.courseIds.includes(courseId));
}

export function getScalesForClass(courseId: string, classNumber: number): CourseScaleItem[] {
  return COURSE_SCALES_DATA.filter(
    (scale) => scale.courseIds.includes(courseId) && (scale.classNumbers?.includes(classNumber) ?? false)
  );
}
